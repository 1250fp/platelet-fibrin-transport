def prepare():
    if (OUT/'protocol.json').exists():
        validate_protocol(load(OUT/'protocol.json'))
        print('Preparation already complete and verified; protected artifacts unchanged.', flush=True)
        return
    for name in ('states', 'initials', 'shared', 'transport', 'regression', 'source_protocols'):
        (OUT/name).mkdir(exist_ok=True)
    status('preparing', phase='protocol_and_source_audit')
    old, reused = audit_previous()
    plan = load(protect(BATCH/'batch_manifest.json'))
    complete = load(protect(BATCH/'completed_runs.json'))
    final = load(protect(BATCH/'execution_summary.json'))
    assert final['completed'] and final['stacks'] == 36 and final['layers'] == 1800 and final['target_time_s'] == 15
    assert plan['workers'] == 8 and not plan['run_transport'] and len(plan['jobs']) == 36
    mapping = {(int(x['replica']), float(x['f0_nN'])): x for x in complete}
    assert len(mapping) == 36 and set(mapping) == {(r, f) for r in range(1, 10) for f in (0., 2.2, 4.4, 8.8)}
    for row in complete:
        assert row['status'] == 'completed' and row['transport_run'] is False and row['final_time_s'] == 15
    raster = prepare_sources(old)
    regression(raster)
    for folder, replicas, _ in PREVIOUS:
        for name in ('protocol.json', 'execution_summary.json'):
            copy_exact(folder/name, OUT/'source_protocols'/folder.name/name)
    seedsets, baselines = {}, {}
    allstates, registry = [], {}
    for rep in range(1, 10):
        atomic_text_array(OUT/'shared'/f'release_candidates_rep{rep}.tsv', base.candidates(rep))
        rng = np.random.default_rng(np.random.SeedSequence([919201, rep]))
        xyz = rng.random((MC, 3))*[47.6, 47.6, 5]+[-23.8, -23.8, 0]
        atomic_text_array(OUT/'shared'/f'volume_rep{rep}.tsv', xyz)
        protect(OUT/'shared'/f'release_candidates_rep{rep}.tsv')
        protect(OUT/'shared'/f'volume_rep{rep}.tsv')
    for job in sorted(plan['jobs'], key=lambda x: (x['replica'], x['f0_nN'])):
        rep, force = int(job['replica']), float(job['f0_nN'])
        source_paths = [Path(p) for p in job['source_layers']]
        assert len(source_paths) == len(job['seeds']) == len(set(job['seeds'])) == 50
        if rep in seedsets:
            assert seedsets[rep] == job['seeds']
        else:
            seedsets[rep] = job['seeds']
        if rep <= 6 and rep not in baselines:
            assert force == 0
            baselines[rep] = baseline(rep, job)
        row = mapping[(rep, force)]
        continued_run = Path(row['run_directory'])
        assert str(Path(row['source_run'])) == str(Path(job['original_run']))
        continuation = load(protect(continued_run/'continuation_manifest.json'))
        assert continuation['source_time_s'] == 10 and continuation['target_time_s'] == 15
        assert all(x['policy'] == 'exact_saved_rng_state' for x in continuation['rng_policy_by_layer'])
        continued_paths = [continued_run/'mechanical_layers'/f'layer_{k+1:03d}_seed{seed}'
                           for k, seed in enumerate(job['seeds'])]
        sets = ([(source_paths, [0., 5., 10.], Path(job['original_run']), None)] if rep >= 7 else [])
        sets.append((continued_paths, [15.], continued_run, source_paths))
        for paths, times, run_dir, parents in sets:
            restored, missing = {}, []
            for tm in times:
                sid = state_id(rep, force, tm)
                st = restore_state(sid, registry)
                if st is None:
                    missing.append(tm)
                else:
                    restored[tm] = st
                    if tm == 0 and rep not in baselines:
                        baselines[rep] = st['common_area_um2'], st['mean_support_area_um2']
            status('preparing', phase='geometry', replicate=rep, f0_nN=force,
                   mechanical_times_s=times, completed_states=len(allstates))
            geometries = rebuild(paths, missing, raster, parents=parents) if missing else {}
            for tm in times:
                sid = state_id(rep, force, tm)
                if tm in restored:
                    st = restored[tm]
                    assert np.allclose([st['baseline_common_area_um2'], st['baseline_mean_support_area_um2']], baselines[rep], rtol=0, atol=1e-10)
                else:
                    g = geometries[tm]
                    assert [m['seed'] for m in g['metadata']] == job['seeds']
                    st = store_state(sid, job, run_dir, tm, g, baselines, registry)
                allstates.append(st)
                print(f'GEOMETRY ready: {sid} ({len(allstates)}/{NOMINAL_STATES}).', flush=True)
    assert len(set(seed for seeds in seedsets.values() for seed in seeds)) == 450
    assert len(allstates) == NOMINAL_STATES and len(registry) == UNIQUE_STATES
    states = [s for s in allstates if s['unique_geometry']]
