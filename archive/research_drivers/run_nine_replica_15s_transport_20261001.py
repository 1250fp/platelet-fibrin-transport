def geometry_job(st):
    dest = OUT/'states'/st['state_id']
    complete = dest/'geometry.done.json'
    previous = verified_marker(complete)
    if previous:
        return previous['result']
    # A marker-free partial analysis is preserved before recomputation. No input
    # or prepared-geometry file is rewritten during execution.
    for p in [dest/'connectivity', dest/'volume_clearance.tsv', dest/'volume_samples.npz']:
        if p.exists():
            quarantine(p)
    result = base.geometry_job(st)
    summary = load(dest/'connectivity/summary.json')
    assert summary['completed'] and summary['N'] == N
    with np.load(dest/'connectivity/initial_connectivity.npz', allow_pickle=False) as a:
        assert len(a['status']) == N and np.isin(a['status'], [-1, 0, 1]).all()
        assert np.array_equal(a['xyz_um'], np.loadtxt(st['initial']))
    files = list((dest/'connectivity').iterdir()) + [dest/'volume_clearance.tsv', dest/'volume_samples.npz']
    assert all(p.is_file() for p in files)
    inputs = {p: sha(p) for p in (st['scene'], st['domain'], st['initial'])}
    marker(complete, files, inputs, result=result)
    return result


def run():
    p = load(OUT/'protocol.json')
    validate_protocol(p)
    if (OUT/'execution_summary.json').exists():
        previous = load(OUT/'execution_summary.json')
        assert previous['completed'] and len(previous['jobs']) == TRANSPORT_JOBS
        for s in p['states']:
            assert verified_marker(OUT/'states'/s['state_id']/'geometry.done.json')
        for job in p['jobs']:
            done = Path(job['output']).with_suffix('.done.json')
            assert done.exists()
            q = load(done)
            assert q['job'] == job and q['exit_code'] == 0 and q['sha256'] == sha(job['output'])
        print('All geometry and transport already completed and verified; nothing rerun.', flush=True)
        return
    transport.EXE = SNAP/'transport_reflection_long.exe'
    started = time.monotonic()
    done, geometry = [], []
    status('running', phase='geometry_and_transport', workers=WORKERS,
           geometry_done=0, geometry_total=UNIQUE_STATES, transport_done=0, transport_total=TRANSPORT_JOBS)
    geometry_queue, transport_queue = deque(p['states']), deque(p['jobs'])
    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        futures = {}
        while geometry_queue or transport_queue or futures:
            # Geometry grids retain sizeable temporary NumPy arrays. Limit these
            # to two, while using the remaining slots for independent C++ jobs.
            while len(futures) < WORKERS:
                active_geometry = sum(kind == 'geometry' for kind in futures.values())
                if geometry_queue and active_geometry < MAX_GEOMETRY_WORKERS:
                    futures[pool.submit(geometry_job, geometry_queue.popleft())] = 'geometry'
                elif transport_queue:
                    futures[pool.submit(transport.execute, transport_queue.popleft())] = 'transport'
                else:
                    break
            ready, _ = wait(futures, return_when=FIRST_COMPLETED)
            for f in ready:
                kind = futures.pop(f)
                try:
                    result = f.result()
                except BaseException:
                    for pending in futures:
                        pending.cancel()
                    raise
                (geometry if kind == 'geometry' else done).append(result)
                status('running', phase='geometry_and_transport', workers=WORKERS,
                       max_geometry_workers=MAX_GEOMETRY_WORKERS,
                       geometry_done=len(geometry), geometry_total=UNIQUE_STATES,
                       transport_done=len(done), transport_total=TRANSPORT_JOBS, elapsed_s=time.monotonic()-started)
                print(f'COMPLETED {kind}: geometry {len(geometry)}/{UNIQUE_STATES}; transport {len(done)}/{TRANSPORT_JOBS}.', flush=True)
    check_hashes(p['source_sha256'])
    assert len(done) == TRANSPORT_JOBS and len(geometry) == UNIQUE_STATES
    base.csvsave(OUT/'connectivity_summary.csv', geometry)
    save(OUT/'execution_summary.json', dict(completed=True, jobs=done, connectivity=geometry,
        wall_s=time.monotonic()-started, source_unchanged=True, scientific_analysis_deferred=True,
        workers=WORKERS, reused_cohorts=p['reused_cohorts'], final_cohort=p['final_cohort']))
    status('completed_awaiting_analysis', geometry_done=UNIQUE_STATES, transport_done=TRANSPORT_JOBS,
           workers=WORKERS, wall_s=time.monotonic()-started)
    print('FINISHED: complete raw results ready; no interim scientific analysis or manuscript edits.', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['prepare', 'run', 'all'])
    args = parser.parse_args()
    with exclusive_execution():
        try:
            if args.mode in ('prepare', 'all'):
                prepare()
            if args.mode in ('run', 'all'):
                run()
        except BaseException as exc:
            status('failed', error=str(exc), failure_is_censoring=False)
            raise


if __name__ == '__main__':
    main()
