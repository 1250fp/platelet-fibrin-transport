def check_hashes(mapping, register=False):
    for path, digest in mapping.items():
        assert Path(path).is_file() and sha(path) == digest, f'Hash mismatch: {path}'
        if register:
            previous = base.protected.get(path)
            assert previous is None or previous == digest, f'Input changed: {path}'
            base.protected[path] = digest


@contextmanager
def exclusive_execution():
    """OS-owned lock releases after a crash; a stale PID cannot block recovery."""
    import msvcrt
    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT/'execution.lock').open('a+b') as handle:
        if handle.tell() == 0:
            handle.write(b'0')
            handle.flush()
        handle.seek(0)
        try:
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError as exc:
            raise RuntimeError('Another preparation/transport process owns this cohort') from exc
        try:
            yield
        finally:
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)


def quarantine(path):
    """Preserve incomplete files generated by this runner; never touch sources."""
    path = Path(path)
    assert path.resolve().is_relative_to(OUT.resolve()) and path.resolve() != OUT.resolve()
    root = OUT/'preparation_recovery'
    root.mkdir(exist_ok=True)
    target = root/f'{path.name}_{time.time_ns()}'
    assert target.resolve().is_relative_to(OUT.resolve())
    path.rename(target)
    print(f'PRESERVED partial generated artifact: {target}', flush=True)


def copy_exact(source, target):
    source, target = Path(source), Path(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    digest = sha(protect(source))
    if target.exists():
        assert sha(target) == digest, f'Existing snapshot changed: {target}'
    else:
        temp = target.with_name(target.name+'.tmp')
        shutil.copy2(source, temp)
        temp.replace(target)
    protect(target)


def atomic_text_array(path, array):
    path = Path(path)
    if path.exists():
        assert np.array_equal(np.loadtxt(path, ndmin=2), np.asarray(array).reshape(len(array), -1)), path
        return
    temp = path.with_name(path.name+'.tmp')
    np.savetxt(temp, array, fmt='%.17g')
    temp.replace(path)


def marker(path, files, inputs=None, **extra):
    save(path, dict(completed=True, files_sha256={str(p): sha(p) for p in files},
                    input_sha256=inputs or {}, **extra))


def verified_marker(path, register=False):
    path = Path(path)
    if not path.exists():
        return None
    value = load(path)
    assert value['completed'] is True
    check_hashes(value['files_sha256'], register)
    check_hashes(value.get('input_sha256', {}), register)
    if register:
        protect(path)
    return value


def audit_previous():
    old = load(protect(OLD/'protocol.json'))
    for field, expected in [('N', N), ('T', HORIZON), ('dt_s', DT), ('radius_um', RADIUS),
                            ('D_um2_s', DIFFUSION), ('H_um', H)]:
        assert old[field] == expected, (field, old[field], expected)
    reused = []
    for folder, replicas, chunks in PREVIOUS:
        protocol = load(protect(folder/'protocol.json'))
        summary = load(protect(folder/'execution_summary.json'))
        assert summary['completed'] and len(summary['jobs']) == chunks
        assert len(protocol['states']) == 9*len(replicas)
        check_hashes(protocol['source_sha256'])
        for result in summary['jobs']:
            assert result['exit_code'] == 0
            # The first pilot reused four fine-step validation chunks in their
            # original directory. Its logical job output is not a copied CSV.
            actual_output = result.get('output', result['job']['output'])
            if result.get('reused', False):
                assert actual_output == result['job']['reuse_output']
            assert sha(protect(actual_output)) == result['sha256']
        reused.append(dict(root=str(folder), replicas=list(replicas), unique_states=9*len(replicas),
                           completed_chunks=chunks, histories=9*len(replicas)*N))
    return old, reused


